const segmenter = new Intl.Segmenter('en', {granularity: 'grapheme'});

/**
 * Creates the HTML room element as a div tag and applies styles to this element
 * @param roomName name to be displayed on in the element
 * @param deleteFunction Method that determines the action when the delete button
 * in the element is clicked
 * @returns {HTMLDivElement} the created HTML element that can be added to the
 */
export function createRoomElement(roomName, deleteFunction) {
  const roomNameWithCommas = roomName.replaceAll(/!/g, ',');
  const roomDiv = document.createElement('div');
  roomDiv.className = 'room-item';
  roomDiv.classList.add('room-div')
  roomDiv.dataset.roomName = roomName; // Store room name for reference

  const nameSpan = document.createElement('span');
  nameSpan.textContent = roomNameWithCommas;
  nameSpan.className = 'room-name-span';

  const deleteButton = document.createElement('button');
  deleteButton.className = 'remove-btn';
  deleteButton.textContent = '×';
  deleteButton.type = 'button';

  deleteButton.onclick = function (event) {
    event.preventDefault();
    deleteFunction(roomName, roomDiv);
  };

  roomDiv.appendChild(nameSpan);
  roomDiv.appendChild(deleteButton);

  return roomDiv;
}

window.createRoomElement = createRoomElement;

/**
 * Create a hidden input element so that thyme leaf/bootstrap can collect the
 * value from these elements when a form is submitted.
 * @param roomName the name of the room and the value collected by the form
 * @returns {HTMLInputElement} HTML input element of hidden type meaning that it
 * doesn't affect the layout of the page
 */
export function createHiddenElement(roomName) {
  const roomNameNoCommas = roomName.replace(/,/g, '!');
  const hiddenInput = document.createElement('input');
  hiddenInput.type = 'hidden';
  hiddenInput.name = 'roomNames';
  hiddenInput.value = roomNameNoCommas;
  hiddenInput.className = 'room-input';
  return hiddenInput;
}

window.createHiddenElement = createHiddenElement;

function countGraphemeClusters(str) {
  return [...segmenter.segment(str)].length;
}

/**
 * Validation function for room names to check for not allowed characters or
 * too many characters.
 * @param roomName name of the room to be validated.
 * @returns {string} error message, or undefined if no error was found.
 */
export function validateRoom(roomName) {
  let error;
  const characterErrorMessage = "Room names can only include letters, numbers, spaces, commas,"
      +
      " dots, hyphens, and apostrophes";
  const tooLongErrorMessage = "Room name must be 255 characters or less";
  // pattern generated by ChatGPT
  const pattern = /^[\p{L}\p{N}\p{M}.,' ་-]+$/u; // Ensure Thymeleaf does not parse this incorrectly
  if (countGraphemeClusters(roomName.trim()) > 255) {
    error = tooLongErrorMessage;
  } else if (!pattern.test(roomName)) {
    error = characterErrorMessage;
  }
  return error;
}

/**
 * This is used when the page loads so that any input for the room name still
 * has an error message displayed if the form has some other error on it
 * and the user has clicked submit.
 *
 * @param roomNameInput input element where the user enters the room name.
 * @param roomError element for the front end room error message.
 */
export function setRoomErrorMessage(roomNameInput, roomError) {
  const roomName = roomNameInput.value.trim()
  if (roomName) {
    const error = validateRoom(roomName);
    if (error === undefined) {
      roomError.hidden = true;
      roomError.innerText = "";
      roomNameInput.classList.remove('is-invalid');
    } else {
      roomNameInput.classList.add('is-invalid');
      roomError.innerText = error;
      roomError.hidden = false;
    }
  }
}
